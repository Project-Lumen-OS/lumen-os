def component(rel, data=None):
    """'own', a COMPONENTS key, or 'meta'."""
    if META.match(rel):
        return "meta"
    for rx, key in RULES:
        if rx.search(rel):
            return key
    if data is not None:
        head = data[:HEAD]
        for prx, crx, key in CONTENT_RULES:
            if prx.search(rel) and crx.search(head):
                return key
    return "own"


def licence_of(key):
    return OWN if key == "own" else ("" if key == "meta" else COMPONENTS[key][1])


def ext(rel):
    return rel.rsplit(".", 1)[-1].lower() if "." in os.path.basename(rel) else ""


def problems(rel, data):
    """The licence problems of one file."""
    key = component(rel, data)
    if key == "meta":
        return []
    head = SNIPPET.sub(b"", data)[:HEAD]
    ids = [m.group(1).decode() for m in SPDX.finditer(head)]
    out = []
    if rel in SNIPPETS:
        snip = SNIPPET.findall(data)
        if not snip or any(SPDX.search(x) is None or SPDX.search(x).group(1) != b"Apache-2.0" for x in snip):
            out.append(f"the Apache-2.0 snippet of {SNIPPETS[rel][1]} is gone or names another licence")
    if key == "own":
        if ext(rel) in CODE_EXT and OWN not in ids:
            out.append(f"own source without 'SPDX-License-Identifier: {OWN}' (run tools/ota/licences.py fix)")
        if [i for i in ids if i != OWN]:
            out.append(f"own file names another licence: {', '.join(i for i in ids if i != OWN)}")
        if APACHE_PROSE.search(head):
            out.append("own file header still says 'Licensed under the Apache License'")
    elif any("PolyForm" in i for i in ids) or b"PolyForm" in head:
        out.append(f"third-party file ({COMPONENTS[key][0]}, {COMPONENTS[key][1]}) carries the Lumen licence")
    return out


def fixed(rel, data):
    """data with the own SPDX header (own files only; anything else comes back unchanged)."""
    if component(rel, data) != "own":
        return data
    head, tail = data[:HEAD], data[HEAD:]
    if SNIPPET.search(head):
        return data
    head = SPDX.sub(lambda m: m.group(0) if m.group(1) == OWN.encode() or not re.search(rb"Apache|PolyForm", m.group(1))
                    else b"SPDX-License-Identifier: " + OWN.encode(), head)
    head = APACHE_PROSE.sub(b"", head)
    data = head + tail
    c = CODE_EXT.get(ext(rel))
    if c is None or OWN.encode() in data[:HEAD]:
        return data
    lines = data.split(b"\n")
    at = 0
    while at < len(lines) and at < 2 and (lines[at].startswith(b"#!") or lines[at].startswith(b"#version")
                                          or re.match(rb"#.*coding[:=]", lines[at])):
        at += 1
    lines.insert(at, c.encode() + b" SPDX-License-Identifier: " + OWN.encode())
    return b"\n".join(lines)


def generated(rel, text):
    """The text a generator writes to rel (path from the tree root, str): its output with the own header as `fix`
    writes it. Generators write this and compare with current(), so the header has one source (OWN, CODE_EXT and
    fixed() here) and no generator or check carries a copy of it."""
    return fixed(rel, text.encode("utf-8")).decode("utf-8")


def unheaded(text):
    """text (str) without the own header line `fix` writes, for a generator that copies an own source into a file
    with its own first line: generated() puts the header of the copy on top."""
    m = re.search(r"(?m)^(?:%s) SPDX-License-Identifier: %s\n" % ("|".join(map(re.escape, sorted(set(CODE_EXT.values())))),
                                                             re.escape(OWN)), text[:HEAD])
    return text if m is None else text[:m.start()] + text[m.end():]


def current(rel, have, want):
    """True when the file text have (None: no file) is the generator output want, the own header aside: a file
    `fix` gave the header and one the header never reached are both current, any other difference is not."""
    return have is not None and generated(rel, have) == generated(rel, want)


