def without_licensor(rel, data):
    """data without the licensor's name where it belongs (NAMED files, the README licence block), and without the
    names of the credited contributors in NAMED files (NOTICE and THIRD_PARTY_NOTICES.md credit them)."""
    name = HOLDER.encode()
    if NAMED.match(rel):
        for who in CREDITED:
            data = data.replace(who, b"")
        return data.replace(name, b"")
    if NAMED_BLOCK.search(rel):
        a, b = data.find(BEGIN.encode()), data.find(END.encode())
        if 0 <= a < b:
            return data[:a] + data[a:b].replace(name, b"") + data[b:]
    return data


def files_of(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                             capture_output=True, check=True).stdout
        rels = [f for f in out.decode().split("\0") if f]
    except (subprocess.CalledProcessError, FileNotFoundError):
        rels = [os.path.relpath(os.path.join(dp, f), root) for dp, dns, fns in os.walk(root)
                for f in fns if ".git" not in dp.split(os.sep)]
    return [r for r in rels if os.path.isfile(os.path.join(root, r)) and not os.path.islink(os.path.join(root, r))]


def read(root, rel):
    with open(os.path.join(root, rel), "rb") as f:
        return f.read()


def applies(root):
    """True for a tree that carries this licence set (its NOTICE has the Required Notice line)."""
    try:
        return b"Required Notice:" in read(root, "NOTICE")
    except OSError:
        return False


def root_problems(root):
    out = []
    lic = LICENCES[OWN]
    try:
        if not read(root, "LICENSE").startswith(b"# " + lic["title"].encode()):
            out.append(("LICENSE", f"is not the {lic['title']} text"))
    except OSError:
        out.append(("LICENSE", "missing"))
    try:
        notice = read(root, "NOTICE").decode("utf-8", "replace").splitlines()
        if REQUIRED_NOTICE not in notice:
            out.append(("NOTICE", f"has no line '{REQUIRED_NOTICE}'"))
    except OSError:
        out.append(("NOTICE", "missing"))
    for f in ("THIRD_PARTY_NOTICES.md", "TRADEMARKS.md", "LICENSES/Apache-2.0.txt"):
        if not os.path.isfile(os.path.join(root, f)):
            out.append((f, "missing"))
    return out


def check(root, rels=None):
    bad = [(r, w) for r, w in root_problems(root)]
    for rel in rels if rels is not None else files_of(root):
        p = problems(rel, read(root, rel))
        if p:
            bad.append((rel, "; ".join(p)))
    return bad


def fix(root, rels=None):
    changed = []
    for rel in rels if rels is not None else files_of(root):
        data = read(root, rel)
        new = fixed(rel, data)
        if new != data:
            with open(os.path.join(root, rel), "wb") as f:
                f.write(new)
            changed.append(rel)
    return changed


def inventory(root):
    return [(rel, component(rel, read(root, rel))) for rel in sorted(files_of(root))]


