"""catalog.py: the shared string module of Lumen (apps/core/lumen-common-strings, tools/arch/README.md).

Every Lumen TV app ships English plus the same 17 locales. A text that two places show lives once in the module
(English res/values/lumen_strings.xml, the locales generated by apps/i18n/gen.py target strings); apps use it through
string aliases (<string name="their_key">@string/lumen_x</string>), so their code keeps its own keys and the
translations live once. tools/i18n/share.py finds and folds the texts defined twice.

  catalog.py report [APP...]      reuse candidates: strings of APP whose English text equals a module text or a
                                  fully translated string of another app
  catalog.py adopt APP [--check]  make APP use the module: in res/values/ every string whose English and
                                  translations equal a module text becomes an alias to it, and its copies in
                                  res/values-*/ go (--check: exit 1 if adopting would change anything)
  catalog.py validate             every module text in all 17 locales; every alias of every app names an existing
                                  text (of the module or a core module's own res)
Reads the tree only, except adopt, which writes APP's res files. Exit 0, 1 red, 2 usage.
"""
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LOCALES = ["ar", "be", "de", "es", "fr", "it", "ja", "kk", "ko", "pl", "pt", "pt-rBR", "ru", "tr", "uk", "zh-rCN",
           "zh-rTW"]
MODULE = "apps/core/lumen-common-strings"
STRING_RE = re.compile(r'(?ms)^[ \t]*<string\s+name="([^"]+)"([^>]*)>(.*?)</string>[ \t]*\n')



def git_files(pattern):
    out = subprocess.run(["git", "ls-files", pattern], cwd=ROOT, capture_output=True, text=True).stdout
    return [p for p in out.split("\n") if p]


def locale_of(values_dir):
    if values_dir == "values":
        return "en"
    loc = values_dir[len("values-"):]
    return loc if loc in LOCALES else None


def strings_in(path):
    """[(name, attrs, raw inner text, full match span)] of the <string> elements of one file."""
    text = open(path, encoding="utf-8").read()
    return [(m.group(1), m.group(2), m.group(3), m.span()) for m in STRING_RE.finditer(text)]


def load_all():
    """{(app, key): {locale: raw text}} of every translatable string in apps/*/res (aliases included as raw text)."""
    data = {}
    # an app is apps/<app>/res, a body module that is a whole app (apps/core/<module>, module.conf body=yes) or a
    # shared app layer apps/common/<layer>/res (source app common/<layer>, e.g. the projector texts of every model)
    for f in sorted(set(git_files("apps/*/res/values*/*.xml") + git_files("apps/core/*/res/values*/*.xml")
                        + git_files("apps/common/*/res/values*/*.xml"))):
        parts = f.split("/")
        if len(parts) == 6 and parts[1] == "core":            # a core module: source app core/<module>
            parts = [parts[0], "core/" + parts[2]] + parts[3:]
        if len(parts) == 6 and parts[1] == "common":            # a shared app layer: source app common/<layer>
            parts = [parts[0], "common/" + parts[2]] + parts[3:]
        if len(parts) != 5:
            continue
        app, loc = parts[1], locale_of(parts[3])
        if loc is None or not os.path.isfile(os.path.join(ROOT, f)):
            continue
        for name, attrs, raw, _ in strings_in(os.path.join(ROOT, f)):
            if 'translatable="false"' in attrs:
                continue
            data.setdefault((app, name), {})[loc] = raw
    return data


def norm(raw):
    return re.sub(r"\s+", " ", raw.strip())


def module_texts(data):
    """({key: {locale: raw}}, errors): the module's texts, all 18 folders required."""
    texts, errors = {}, []
    for (app, key), v in sorted(data.items()):
        if app != "core/" + os.path.basename(MODULE):
            continue
        miss = [loc for loc in ["en"] + LOCALES if loc not in v]
        if miss:
            errors.append("%s: %s lacks %s" % (MODULE, key, " ".join(miss)))
            continue
        texts[key] = dict(v)
    return texts, errors


def by_english(texts):
    """{normalised English: [module keys]} (one English text in several contexts has several keys)."""
    out = {}
    for k in sorted(texts):
        out.setdefault(norm(texts[k]["en"]), []).append(k)
    return out


def app_translations(res, f, name):
    """{locale: raw} of string NAME of file F in every res/values-<locale>/ of an app."""
    out = {}
    for loc in LOCALES:
        p = os.path.join(res, "values-" + loc, f)
        if os.path.isfile(p):
            for n, attrs, raw, _ in strings_in(p):
                if n == name:
                    out[loc] = raw
    return out


def cmd_adopt(app, check):
    data = load_all()
    texts, errors = module_texts(data)
    if errors:
        for e in errors:
            print("catalog: ERROR " + e)
        return 1
    eng = by_english(texts)
    res = os.path.join(ROOT, "apps", app, "res")
    if not os.path.isdir(res):
        print("catalog: no %s" % res)
        return 2
    alias = {}                                           # key -> module key
    changed, differ = [], []
    for f in sorted(os.listdir(os.path.join(res, "values"))):
        if not f.endswith(".xml"):
            continue
        p = os.path.join(res, "values", f)
        text = open(p, encoding="utf-8").read()
        new = text
        for name, attrs, raw, span in reversed(strings_in(p)):
            if 'translatable="false"' in attrs or raw.startswith("@"):
                continue
            keys = eng.get(norm(raw), [])
            if not keys:
                continue
            have = app_translations(res, f, name)
            # only a true copy is adopted: the app's own translations equal the entry's in every locale the app has
            # (so adopting changes no text); a different translation is another context and stays the app's
            # and the app has the text in all 17 locales (an app shows one language: adopting must not add a locale)
            fit = [k for k in keys if texts[k]["en"] == raw and len(have) == len(LOCALES)
                   and all(texts[k][loc] == t for loc, t in have.items())]
            if not fit:
                differ.append("%s/%s %s: the app's translation differs from %s (another context): kept"
                              % (f, name, norm(raw)[:40], " ".join(keys)))
                continue
            k = fit[0]
            alias[(f, name)] = k
            seg = text[span[0]:span[1]]
            new = new[:span[0]] + seg.replace(">" + raw + "</string>", ">@string/" + k + "</string>") + new[span[1]:]
        if new != text:
            changed.append(os.path.relpath(p, ROOT))
            if not check:
                open(p, "w", encoding="utf-8").write(new)
    for loc in LOCALES:
        d = os.path.join(res, "values-" + loc)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            p = os.path.join(d, f)
            if not f.endswith(".xml"):
                continue
            text = open(p, encoding="utf-8").read()
            new = text
            for name, attrs, raw, span in reversed(strings_in(p)):
                k = alias.get((f, name))
                if not k:
                    continue
                if raw != texts[k][loc]:                  # cannot happen (the fit rule above): never drop a text
                    print("catalog: ERROR %s %s differs from %s" % (loc, name, k))
                    return 1
                new = new[:span[0]] + new[span[1]:]
            if new != text:
                changed.append(os.path.relpath(p, ROOT))
                if not check:
                    open(p, "w", encoding="utf-8").write(new)
    print("catalog: adopt %s: %d string(s) use the shared module, %d file(s) %s" % (
        app, len(alias), len(changed), "would change" if check else "changed"))
    for d in differ:
        print("catalog:   " + d)
    return 1 if (check and changed) else 0


def cmd_validate():
    data = load_all()
    texts, errors = module_texts(data)
    # a core module's own texts (apps/core/*/res, e.g. lumen-remote's lumen_remote_*) are aliased by the apps that
    # carry the module (its recipe), like a shared text
    module_keys = set()
    for f in git_files("apps/core/*/res/values/*.xml"):
        if os.path.isfile(os.path.join(ROOT, f)):
            module_keys |= {name for name, _, _, _ in strings_in(os.path.join(ROOT, f))}
    for (app, key), v in sorted(data.items()):
        en = v.get("en", "")
        m = re.match(r"^@string/(lumen_[a-z0-9_]+)$", en.strip())
        if m and m.group(1) not in texts and m.group(1) not in module_keys:
            errors.append("apps/%s: %s aliases %s, which neither the shared module nor a core module has" % (app, key, m.group(1)))
    for e in errors:
        print("catalog: ERROR " + e)
    print("catalog: validate: %d shared texts, %s" % (len(texts), "RED" if errors else "OK"))
    return 1 if errors else 0


def cmd_report(apps):
    data = load_all()
    texts, errors = module_texts(data)
    eng = by_english(texts)
    full = {}
    for (app, key), v in data.items():
        if "en" in v and all(loc in v for loc in LOCALES) and not v["en"].startswith("@"):
            full.setdefault(norm(v["en"]), []).append((app, key))
    targets = apps or sorted({a for a, _ in data})
    total = 0
    for t in targets:
        keys = sorted(k for a, k in data if a == t and "en" in data[(a, k)])
        cand = []
        for k in keys:
            en = data[(t, k)]["en"]
            if en.startswith("@"):
                continue
            hit = " ".join(eng.get(norm(en), [])) or next(("%s/%s" % s for s in full.get(norm(en), []) if s[0] != t), None)
            if hit:
                cand.append((k, norm(en), hit))
        total += len(cand)
        print("%s: %d strings, %d reuse candidate(s)" % (t, len(keys), len(cand)))
        for k, en, hit in cand:
            print("  %s = %s  (%s)" % (k, en[:60], hit))
    for e in errors:
        print("catalog: ERROR " + e)
    return 1 if errors else 0


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    c, rest = argv[0], argv[1:]
    if c == "adopt" and len(rest) in (1, 2) and (len(rest) == 1 or rest[1] == "--check"):
        return cmd_adopt(rest[0], len(rest) == 2)
    if c == "validate" and not rest:
        return cmd_validate()
    if c == "report":
        return cmd_report(rest)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
