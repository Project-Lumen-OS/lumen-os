#!/usr/bin/env python3
"""catalog.py: the shared translation vocabulary of Lumen (module apps/core/lumen-common-strings, tools/arch/README.md).

Every Lumen TV app ships English plus the same 17 locales. Before this module each app kept its own copy of every
translation, and a new port re-translated texts that already existed. The vocabulary is a
list of shared texts, each taken byte for byte from one app that already has it translated in all 17 locales; apps use
it through string aliases (<string name="their_key">@string/lumen_x</string>), so their code keeps its own keys and the
translations live once.

  catalog.py report [APP...]      reuse candidates: strings of APP whose English text equals a vocabulary entry or a
                                  fully translated string of another app; conflicts (same English, other translation)
  catalog.py module [--check]     write apps/core/lumen-common-strings/res/values*/lumen_strings.xml from
                                  vocabulary.tsv (--check: compare, write nothing; exit 1 on a difference)
  catalog.py adopt APP [--check]  make APP use the vocabulary: in res/values/ every string whose English equals an entry
                                  becomes an alias to it, and its copies in res/values-*/ go (--check: exit 1 if
                                  adopting would change anything, i.e. APP keeps a copy of a vocabulary text)
  catalog.py validate             the module: every key in all 17 locales, nothing else; every alias of every app
                                  names an existing entry

vocabulary.tsv (apps/core/lumen-common-strings): key <TAB> source app <TAB> source key <TAB> note; '#' comments. The
source must have the text in res/values and in all 17 locales. Keys are lumen_*; a key names a text in one grammatical
context (a second context of the same English is a second key with its own source).
Reads the tree only, except: module writes the module's res files, adopt writes APP's res files. Exit 0, 1 red, 2 usage.
"""
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LOCALES = ["ar", "be", "de", "es", "fr", "it", "ja", "kk", "ko", "pl", "pt", "pt-rBR", "ru", "tr", "uk", "zh-rCN",
           "zh-rTW"]
MODULE = "apps/core/lumen-common-strings"
VOCAB = MODULE + "/vocabulary.tsv"
OUT_NAME = "lumen_strings.xml"
STRING_RE = re.compile(r'(?ms)^[ \t]*<string\s+name="([^"]+)"([^>]*)>(.*?)</string>[ \t]*\n')
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/i18n/catalog.py module from %s: do not edit.\n'
          '     Each text is the source app\'s own translation, byte for byte (column 2 and 3 of the vocabulary). -->\n'
          '<resources>\n')


def git_files(pattern):
    out = subprocess.run(["git", "ls-files", pattern], cwd=ROOT, capture_output=True, text=True).stdout
    return [p for p in out.split("\n") if p]


def locale_of(values_dir):
    if values_dir == "values":
        return "en"
    loc = values_dir[len("values-"):]
    return loc if loc in LOCALES else None


def strings_in(path):
    """[(name, attrs, raw inner text, full match span)] of the <string> elements of one file."""
    text = open(path, encoding="utf-8").read()
    return [(m.group(1), m.group(2), m.group(3), m.span()) for m in STRING_RE.finditer(text)]


def load_all():
    """{(app, key): {locale: raw text}} of every translatable string in apps/*/res (aliases included as raw text)."""
    data = {}
    for f in git_files("apps/*/res/values*/*.xml"):
        parts = f.split("/")
        if len(parts) != 5:
            continue
        app, loc = parts[1], locale_of(parts[3])
        if loc is None or not os.path.isfile(os.path.join(ROOT, f)):
            continue
        for name, attrs, raw, _ in strings_in(os.path.join(ROOT, f)):
            if 'translatable="false"' in attrs:
                continue
            data.setdefault((app, name), {})[loc] = raw
    return data


def norm(raw):
    return re.sub(r"\s+", " ", raw.strip())


def read_vocab():
    rows, errors = [], []
    path = os.path.join(ROOT, VOCAB)
    if not os.path.isfile(path):
        return rows, ["no %s" % VOCAB]
    seen = set()
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        p = line.rstrip("\n").split("\t")
        if len(p) < 3 or not re.match(r"^lumen_[a-z0-9_]+$", p[0]):
            errors.append("%s:%d: want key<TAB>app<TAB>source key[<TAB>note], key lumen_*" % (VOCAB, n))
            continue
        if p[0] in seen:
            errors.append("%s:%d: %s twice" % (VOCAB, n, p[0]))
        seen.add(p[0])
        rows.append((p[0], p[1], p[2], p[3] if len(p) > 3 else "", n))
    return rows, errors


def vocab_texts(data):
    """({key: {locale: raw}}, errors): each vocabulary row resolved from its source, all 18 folders required."""
    rows, errors = read_vocab()
    out = {}
    for key, app, skey, _, n in rows:
        src = data.get((app, skey))
        if not src:
            errors.append("%s:%d: %s/%s does not exist" % (VOCAB, n, app, skey))
            continue
        miss = [loc for loc in ["en"] + LOCALES if loc not in src]
        if miss:
            errors.append("%s:%d: %s/%s lacks %s" % (VOCAB, n, app, skey, " ".join(miss)))
            continue
        if src["en"].startswith("@"):
            errors.append("%s:%d: %s/%s is itself an alias" % (VOCAB, n, app, skey))
            continue
        out[key] = dict(src)
    return out, errors


def module_files(texts):
    files = {}
    for loc in ["en"] + LOCALES:
        d = "values" if loc == "en" else "values-" + loc
        body = "".join('    <string name="%s">%s</string>\n' % (k, texts[k][loc]) for k in sorted(texts))
        files["%s/res/%s/%s" % (MODULE, d, OUT_NAME)] = HEADER % VOCAB + body + "</resources>\n"
    return files


def cmd_module(check):
    data = load_all()
    texts, errors = vocab_texts(data)
    if errors:
        for e in errors:
            print("catalog: ERROR " + e)
        return 1
    bad = 0
    for rel, body in sorted(module_files(texts).items()):
        p = os.path.join(ROOT, rel)
        old = open(p, encoding="utf-8").read() if os.path.isfile(p) else None
        if old == body:
            continue
        if check:
            print("catalog: %s is not what vocabulary.tsv generates" % rel)
            bad = 1
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w", encoding="utf-8").write(body)
            print("catalog: wrote " + rel)
    print("catalog: module: %d texts x %d folders%s" % (len(texts), 1 + len(LOCALES), " (check)" if check else ""))
    return bad


def by_english(texts):
    """{normalised English: [vocabulary keys]} (one English text in several contexts has several keys)."""
    out = {}
    for k in sorted(texts):
        out.setdefault(norm(texts[k]["en"]), []).append(k)
    return out


def app_translations(res, f, name):
    """{locale: raw} of string NAME of file F in every res/values-<locale>/ of an app."""
    out = {}
    for loc in LOCALES:
        p = os.path.join(res, "values-" + loc, f)
        if os.path.isfile(p):
            for n, attrs, raw, _ in strings_in(p):
                if n == name:
                    out[loc] = raw
    return out


def cmd_adopt(app, check):
    data = load_all()
    texts, errors = vocab_texts(data)
    if errors:
        for e in errors:
            print("catalog: ERROR " + e)
        return 1
    eng = by_english(texts)
    res = os.path.join(ROOT, "apps", app, "res")
    if not os.path.isdir(res):
        print("catalog: no %s" % res)
        return 2
    alias = {}                                           # key -> vocabulary key
    changed, differ = [], []
    for f in sorted(os.listdir(os.path.join(res, "values"))):
        if not f.endswith(".xml"):
            continue
        p = os.path.join(res, "values", f)
        text = open(p, encoding="utf-8").read()
        new = text
        for name, attrs, raw, span in reversed(strings_in(p)):
            if 'translatable="false"' in attrs or raw.startswith("@"):
                continue
            keys = eng.get(norm(raw), [])
            if not keys:
                continue
            have = app_translations(res, f, name)
            # only a true copy is adopted: the app's own translations equal the entry's in every locale the app has
            # (so adopting changes no text); a different translation is another context and stays the app's
            fit = [k for k in keys if texts[k]["en"] == raw and all(texts[k][loc] == t for loc, t in have.items())]
            if not fit:
                differ.append("%s/%s %s: the app's translation differs from %s (another context): kept"
                              % (f, name, norm(raw)[:40], " ".join(keys)))
                continue
            k = fit[0]
            alias[(f, name)] = k
            seg = text[span[0]:span[1]]
            new = new[:span[0]] + seg.replace(">" + raw + "</string>", ">@string/" + k + "</string>") + new[span[1]:]
        if new != text:
            changed.append(os.path.relpath(p, ROOT))
            if not check:
                open(p, "w", encoding="utf-8").write(new)
    for loc in LOCALES:
        d = os.path.join(res, "values-" + loc)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            p = os.path.join(d, f)
            if not f.endswith(".xml"):
                continue
            text = open(p, encoding="utf-8").read()
            new = text
            for name, attrs, raw, span in reversed(strings_in(p)):
                k = alias.get((f, name))
                if not k:
                    continue
                if raw != texts[k][loc]:                  # cannot happen (the fit rule above): never drop a text
                    print("catalog: ERROR %s %s differs from %s" % (loc, name, k))
                    return 1
                new = new[:span[0]] + new[span[1]:]
            if new != text:
                changed.append(os.path.relpath(p, ROOT))
                if not check:
                    open(p, "w", encoding="utf-8").write(new)
    print("catalog: adopt %s: %d string(s) use the vocabulary, %d file(s) %s" % (
        app, len(alias), len(changed), "would change" if check else "changed"))
    for d in differ:
        print("catalog:   " + d)
    return 1 if (check and changed) else 0


def cmd_validate():
    data = load_all()
    texts, errors = vocab_texts(data)
    for rel, body in module_files(texts).items():
        p = os.path.join(ROOT, rel)
        if not os.path.isfile(p) or open(p, encoding="utf-8").read() != body:
            errors.append("%s is stale: run catalog.py module" % rel)
    for (app, key), v in sorted(data.items()):
        en = v.get("en", "")
        m = re.match(r"^@string/(lumen_[a-z0-9_]+)$", en.strip())
        if m and app != "core" and m.group(1) not in texts:
            errors.append("apps/%s: %s aliases %s, which the vocabulary does not have" % (app, key, m.group(1)))
    for e in errors:
        print("catalog: ERROR " + e)
    print("catalog: validate: %d vocabulary texts, %s" % (len(texts), "RED" if errors else "OK"))
    return 1 if errors else 0


def cmd_report(apps):
    data = load_all()
    texts, errors = vocab_texts(data)
    eng = by_english(texts)
    full = {}
    for (app, key), v in data.items():
        if "en" in v and all(loc in v for loc in LOCALES) and not v["en"].startswith("@"):
            full.setdefault(norm(v["en"]), []).append((app, key))
    targets = apps or sorted({a for a, _ in data})
    total = 0
    for t in targets:
        keys = sorted(k for a, k in data if a == t and "en" in data[(a, k)])
        cand = []
        for k in keys:
            en = data[(t, k)]["en"]
            if en.startswith("@"):
                continue
            hit = " ".join(eng.get(norm(en), [])) or next(("%s/%s" % s for s in full.get(norm(en), []) if s[0] != t), None)
            if hit:
                cand.append((k, norm(en), hit))
        total += len(cand)
        print("%s: %d strings, %d reuse candidate(s)" % (t, len(keys), len(cand)))
        for k, en, hit in cand:
            print("  %s = %s  (%s)" % (k, en[:60], hit))
    for e in errors:
        print("catalog: ERROR " + e)
    return 1 if errors else 0


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    c, rest = argv[0], argv[1:]
    if c == "module" and rest in ([], ["--check"]):
        return cmd_module(rest == ["--check"])
    if c == "adopt" and len(rest) in (1, 2) and (len(rest) == 1 or rest[1] == "--check"):
        return cmd_adopt(rest[0], len(rest) == 2)
    if c == "validate" and not rest:
        return cmd_validate()
    if c == "report":
        return cmd_report(rest)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
