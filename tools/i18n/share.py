"""share.py: every text of Lumen is defined once (apps/core/lumen-common-strings, tools/arch/README.md).

A text that two places show (two apps, an app and a core module, two keys of one module) lives once in the shared
string module apps/core/lumen-common-strings (English in res/values/lumen_strings.xml, the 17 locales generated by
apps/i18n/gen.py from apps/i18n/langs/<locale>.txt, section @strings/lumen_strings.xml). Every other place keeps its
own key (and so its code) as an alias: <string name="their_key">@string/lumen_x</string> in res/values only.

  share.py check            the guard: exit 1 when one English text is defined (not as an alias) in two places,
                            unless known_dups.tsv names exactly that set of places with the reason it cannot be one
                            text yet; a row that no longer matches is an error too (the list only shrinks)
  share.py report [-v]      the duplicate groups and why each one is kept
  share.py known            rewrite known_dups.tsv from the tree (after apply, or when a row was fixed by hand):
                            review its diff, a new row is a new copy
  share.py apply            fold every group that can be one text: same English, same attributes, the same
                            translation in all 17 locales, every place built through an app recipe (so the module can
                            be named there); writes the module, the aliases, langs/*.txt, the recipes (module line)
                            and the modules' depends=, then run apps/i18n/gen.py --write --only strings

A group is kept (known_dups.tsv) when its translations differ (another grammatical context, or a translation that
still has to be agreed), when a place lacks locales (an app shows English for those), when a place is built without
a recipe (LumenInfo, LumenKeyboard, LumenMiracast, Z9xTvInput's LumenTvInput) or the text has markup.
Exit 0 green, 1 red, 2 usage.
"""
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = os.environ.get("SHARE_ROOT") or os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
LOCALES = ["ar", "be", "de", "es", "fr", "it", "ja", "kk", "ko", "pl", "pt", "pt-rBR", "ru", "tr", "uk", "zh-rCN",
           "zh-rTW"]
MODULE = "apps/core/lumen-common-strings"
MODULE_FILE = "lumen_strings.xml"
KNOWN = MODULE + "/known_dups.tsv"
MODULE_NOTE = "# the shared texts (apps/core/lumen-common-strings): every text two places show, once"
STRING_RE = re.compile(r'(?ms)^[ \t]*<string\s+name="([^"]+)"([^>]*)>(.*?)</string>[ \t]*\n')
# the translation sources of the generated texts: apps/i18n/gen.py (langs, and pending translations not merged yet)
LANG_DIRS = ["apps/i18n/langs", "apps/i18n/pending/*"]
# generated units -> their section app name (apps/i18n/gen.py RES)
GEN = {"apps/LumenProjector/core": "projector", "apps/LumenTvInput": "tvinput", "apps/LumenAirPlay": "airplay",
       "apps/LumenHome": "home", "apps/LumenSetup": "setup", "apps/core/lumen-updater": "updater",
       "apps/LumenMiracast": "miracast", "apps/common/projector": "common", MODULE: "strings"}


def git_files(pattern):
    out = subprocess.run(["git", "ls-files", pattern], cwd=ROOT, capture_output=True, text=True).stdout
    return [p for p in out.split("\n") if p and os.path.isfile(os.path.join(ROOT, p))]


def norm(raw):
    return re.sub(r"\s+", " ", raw.strip())


def strings_in(path):
    text = open(path, encoding="utf-8").read()
    return [(m.group(1), m.group(2), m.group(3), m.span()) for m in STRING_RE.finditer(text)]


def load():
    """{unit: {loc: {name: (file, attrs, raw)}}} of every <string> under apps/*/res and apps/*/*/res."""
    units = {}
    for f in git_files("apps/*res/values*/*.xml"):
        parts = f.split("/")
        i = parts.index("res")
        if i + 3 != len(parts):
            continue
        unit, vdir = "/".join(parts[:i]), parts[i + 1]
        loc = "en" if vdir == "values" else vdir[len("values-"):]
        if loc != "en" and loc not in LOCALES:
            continue
        for name, attrs, raw, _ in strings_in(os.path.join(ROOT, f)):
            units.setdefault(unit, {}).setdefault(loc, {})[name] = (parts[-1], attrs, raw)
    return units


def defs(units):
    """{(unit, name): {"file", "attrs", "en", "tr": {loc: raw}}} of the translatable texts that are not aliases."""
    out = {}
    for unit, by_loc in units.items():
        for name, (f, attrs, raw) in by_loc.get("en", {}).items():
            if 'translatable="false"' in attrs or raw.strip().startswith("@"):
                continue
            tr = {loc: by_loc[loc][name][2] for loc in LOCALES if name in by_loc.get(loc, {})}
            out[(unit, name)] = {"file": f, "attrs": norm(attrs), "en": raw, "tr": tr}
    return out


def groups(d):
    by = {}
    for k in sorted(d):
        by.setdefault(norm(d[k]["en"]), []).append(k)
    return {en: ks for en, ks in by.items() if len(ks) > 1}


def recipes():
    """[(recipe, {units it assembles}, [module names])] of every *.layers file."""
    dirs = {}
    for line in open(os.path.join(ROOT, "apps/app_dirs.tsv"), encoding="utf-8"):
        p = line.split("#")[0].split()
        if len(p) == 2:
            dirs[p[0]] = p[1]
    out = []
    for f in git_files("*.layers"):
        units, mods, app, tops = set(), [], None, []
        for line in open(os.path.join(ROOT, f), encoding="utf-8"):
            w = line.split("#")[0].split()
            if len(w) < 2:
                continue
            if w[0] == "app":
                app = w[1]
            elif w[0] == "base":
                units.add(w[1].rstrip("/"))
            elif w[0] == "top":
                tops.append(w[1].rstrip("/"))
            elif w[0] == "module":
                m = w[1] if "/" in w[1] else "apps/core/" + w[1]
                units.add(m.rstrip("/"))
                mods.append(os.path.basename(m.rstrip("/")))
        if tops:
            units |= set(tops)
        elif f.startswith("apps/") and f.count("/") == 2:
            units.add(os.path.dirname(f))
        elif app:
            units.add(dirs.get(app, "apps/" + app))
        out.append((f, units, mods))
    return out


def own_texts(unit):
    d = os.path.join(ROOT, unit, "res", "values")
    return os.path.isdir(d) and any('translatable="false"' not in a for f in os.listdir(d) if f.endswith(".xml")
                                    for _, a, _, _ in strings_in(os.path.join(d, f)))


def partial_apps(recs):
    """Units assembled into an app whose own texts lack locales (LumenInstaller, LumenDsuInstall, LumenFiles: English
    and Russian): the module would add 16 locale folders to it, so its places stay copies."""
    out = set()
    for f, units, mods in recs:
        tops = [u for u in units if u.startswith("apps/") and not u.startswith(("apps/core/", "apps/common/"))
                and own_texts(u)]
        if any(not all(os.path.isdir(os.path.join(ROOT, u, "res", "values-" + l)) for l in LOCALES) for u in tops):
            out |= units
    return out


def raw_built(recs):
    """Units some build compiles without a recipe: an app folder named by app_dirs.tsv with no recipe of its own,
    and every app folder no recipe assembles."""
    built = set()
    for _, u, _ in recs:
        built |= u
    raw = set()
    own = {os.path.basename(f)[:-len(".layers")] for f, _, _ in recs}   # every app with a recipe of its own
    for line in open(os.path.join(ROOT, "apps/app_dirs.tsv"), encoding="utf-8"):
        p = line.split("#")[0].split()
        if len(p) == 2 and not os.path.isfile(os.path.join(ROOT, p[1], "app.layers")) and p[0] not in own:
            raw.add(p[1])
    return raw, built


def classify(d, recs):
    """[(English, places, reason or None)]: every duplicated text with every reason it is not one text yet."""
    raw, built = raw_built(recs)
    out = []
    for en, ks in sorted(groups(d).items()):
        why = []
        bad = sorted({u for u, _ in ks if u in raw or u not in built})
        if bad:
            why.append("built without a recipe: " + " ".join(bad))
        part_app = sorted({u for u, _ in ks if u in partial_apps(recs)} - set(bad))
        if part_app:
            why.append("in an app with English and Russian only: " + " ".join(part_app))
        if "<" in en:
            why.append("markup")
        if len({d[k]["attrs"] for k in ks}) > 1:
            why.append("attributes differ")
        part = [k for k in ks if len(d[k]["tr"]) != len(LOCALES)]
        if part:
            why.append("not in all 17 locales: " + " ".join("%s:%s(%d)" % (u, n, len(d[(u, n)]["tr"])) for u, n in part))
        full = [k for k in ks if k not in part]
        if any(d[k]["tr"]["pt"] != d[k]["tr"]["pt-rBR"] for k in full):
            why.append("pt and pt-rBR differ")
        diff = sorted({loc for k in full for loc in LOCALES if d[k]["tr"][loc] != d[full[0]]["tr"][loc]}) if full else []
        if diff:
            why.append("translations differ: " + " ".join(diff))
        out.append((en, ks, "; ".join(why) or None))
    return out


def place(k):
    return "%s:%s" % k


def read_known():
    rows = {}
    p = os.path.join(ROOT, KNOWN)
    if not os.path.isfile(p):
        return rows
    for n, line in enumerate(open(p, encoding="utf-8"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        c = line.rstrip("\n").split("\t")
        rows[c[0]] = (set(c[1].split()), c[2] if len(c) > 2 else "", n)
    return rows


def cmd_check():
    d = defs(load())
    known = read_known()
    errors = []
    for en, ks in sorted(groups(d).items()):
        got = {place(k) for k in ks}
        row = known.get(en)
        if row is None:
            errors.append("%r is defined %d times (%s): make it one text, python3 tools/i18n/share.py apply" % (
                en, len(ks), " ".join(sorted(got))))
        elif row[0] != got:
            errors.append("%s:%d: %r is defined at %s now, the row says %s" % (
                KNOWN, row[2], en, " ".join(sorted(got)), " ".join(sorted(row[0]))))
    for en, (places, _, n) in sorted(known.items(), key=lambda x: x[1][2]):
        if en not in groups(d):
            errors.append("%s:%d: %r is no duplicate any more: drop the row" % (KNOWN, n, en))
    for e in errors:
        print("share: ERROR " + e)
    print("share: check: %d duplicated texts, %d known with a reason, %s" % (
        len(groups(d)), len(known), "RED" if errors else "OK"))
    return 1 if errors else 0


def cmd_report():
    d = defs(load())
    recs = recipes()
    rows = classify(d, recs)
    print("share: %d duplicated texts, %d places; %d sets of places can be one text now (share.py apply)" % (
        len(rows), sum(len(r[1]) for r in rows), len(classes(d, recs))))
    cats = {}
    for en, ks, why in rows:
        cats.setdefault((why or "same translations").split(":")[0], []).append((en, ks, why))
    for c, rs in sorted(cats.items()):
        print("  %-28s %4d texts, %4d places" % (c, len(rs), sum(len(r[1]) for r in rs)))
    if "-v" in sys.argv:
        for en, ks, why in rows:
            print("%s\t%s\t%s" % (en, " ".join(place(k) for k in ks), why or "fold"))
    return 0


KNOWN_HEAD = """# Texts still defined in more than one place, with the reason (tools/i18n/share.py check fails on any other copy).
# English <TAB> places (unit:key) <TAB> reason. The list only shrinks: fold a row with share.py apply once its
# reason is gone (a translation agreed, the app built through a recipe, the missing locales translated).
"""


def cmd_known():
    d = defs(load())
    rows = classify(d, recipes())
    with open(os.path.join(ROOT, KNOWN), "w", encoding="utf-8") as fh:
        fh.write(KNOWN_HEAD)
        for en, ks, why in rows:
            fh.write("%s\t%s\t%s\n" % (en, " ".join(sorted(place(k) for k in ks)), why or "same translations"))
    print("share: known: %d rows in %s" % (len(rows), KNOWN))
    return 0


def slug(en):
    s = re.sub(r"[^a-z0-9]+", "_", en.lower()).strip("_")
    return "_".join(s.split("_")[:5])[:40] or "text"


def edit(path, fn):
    text = open(path, encoding="utf-8").read()
    new = fn(text)
    if new != text:
        open(path, "w", encoding="utf-8").write(new)


def set_raw(path, name, raw):
    def fn(text):
        for n, attrs, old, span in strings_in(path):
            if n == name:
                seg = text[span[0]:span[1]]
                return text[:span[0]] + seg.replace(">" + old + "</string>", ">" + raw + "</string>") + text[span[1]:]
        raise SystemExit("share: %s has no %s" % (path, name))
    edit(path, fn)


def drop(path, name):
    def fn(text):
        for n, _, _, span in strings_in(path):
            if n == name:
                return text[:span[0]] + text[span[1]:]
        return text
    edit(path, fn)
    if not re.search(r"<(string|plurals|string-array|item|dimen|color|bool|integer)\b", open(path, encoding="utf-8").read()):
        os.remove(path)                        # a locale file left with nothing of its own


def add_module_texts(new):
    """new: {key: {"en": raw, "tr": {loc: raw}}}: entries written into the module's res files, sorted by key."""
    for loc in ["en"] + LOCALES:
        p = os.path.join(ROOT, MODULE, "res", "values" if loc == "en" else "values-" + loc, MODULE_FILE)
        text = open(p, encoding="utf-8").read()
        have = {n: raw for n, _, raw, _ in strings_in(p)}
        for k, v in new.items():
            have[k] = v["en"] if loc == "en" else v["tr"][loc]
        head = text[:text.index("<resources>") + len("<resources>\n")]
        body = "".join('    <string name="%s">%s</string>\n' % (k, have[k]) for k in sorted(have))
        open(p, "w", encoding="utf-8").write(head + body + "</resources>\n")


def lang_drop(section, names):
    """Remove the lines of NAMES from section @SECTION of every langs/<locale>.txt."""
    import glob
    for p in sorted(f for d in LANG_DIRS for f in glob.glob(os.path.join(ROOT, d, "*.txt"))):
        out, cur = [], None
        for line in open(p, encoding="utf-8"):
            if line.startswith("@"):
                cur = line[1:].strip()
            elif cur == section and "=" in line and not line.lstrip().startswith("#"):
                if line.split("=", 1)[0].strip().split("#")[0] in names:
                    continue
            out.append(line)
        keep, i = [], 0
        while i < len(out):                    # a section left without a line goes too
            if out[i].startswith("@"):
                j = i + 1
                while j < len(out) and not out[j].startswith("@") and not ("=" in out[j] and not out[j].lstrip().startswith("#")):
                    j += 1
                if j == len(out) or out[j].startswith("@"):
                    i = j
                    continue
            keep.append(out[i])
            i += 1
        open(p, "w", encoding="utf-8").write("".join(keep))


def add_module(recs, units):
    """Name lumen-common-strings in every recipe that assembles one of UNITS, and in depends= of a core module."""
    name = os.path.basename(MODULE)
    for f, u, mods in recs:
        if name in mods or not (u & units):
            continue
        lines = open(os.path.join(ROOT, f), encoding="utf-8").read().split("\n")
        at = next((i for i, l in enumerate(lines) if l.split()[:1] == ["module"]), None)
        if at is None:
            at = max(i for i, l in enumerate(lines) if l.split()[:1] in (["app"], ["base"], ["file"])) + 1
        while at > 0 and lines[at - 1].startswith("#") and lines[at - 2:at - 1] != [""] and at - 1 > 0:
            at -= 1                            # above the comment of the next line
        lines[at:at] = [MODULE_NOTE, "module    %s" % name]
        open(os.path.join(ROOT, f), "w", encoding="utf-8").write("\n".join(lines))
    for unit in sorted(units):
        if not unit.startswith("apps/core/") or unit == MODULE:
            continue
        p = os.path.join(ROOT, unit, "module.conf")
        lines = open(p, encoding="utf-8").read().split("\n")
        i = next((i for i, l in enumerate(lines) if l.startswith("depends=")), None)
        if i is None:
            j = next(i for i, l in enumerate(lines) if l.startswith("package="))
            lines.insert(j + 1, "depends=" + name)
        elif name not in lines[i][len("depends="):].split():
            lines[i] = lines[i] + " " + name
        open(p, "w", encoding="utf-8").write("\n".join(lines))


def classes(d, recs):
    """[(English, [places])]: the places of one text that can be one text, i.e. the same English, attributes and
    translation in all 17 locales (pt = pt-rBR), no markup, every place built through a recipe."""
    raw, built = raw_built(recs)
    raw = raw | partial_apps(recs)
    out = []
    for en, ks in sorted(groups(d).items()):
        by = {}
        for k in ks:
            v = d[k]
            if k[0] in raw or k[0] not in built or "<" in en or len(v["tr"]) != len(LOCALES) \
                    or v["tr"]["pt"] != v["tr"]["pt-rBR"]:
                continue
            by.setdefault((v["attrs"], tuple(sorted(v["tr"].items()))), []).append(k)
        for (attrs, _), cls in sorted(by.items()):
            if len(cls) > 1 and not attrs:
                out.append((en, cls))
    return out


def cmd_apply():
    units = load()
    d = defs(units)
    recs = recipes()
    taken = {n for by_loc in units.values() for n in by_loc.get("en", {})}
    new, aliased, lang, n_alias = {}, set(), {}, 0
    for en, ks in classes(d, recs):
        home = next((n for u, n in ks if u == MODULE), None)
        if home is None:
            home = "lumen_" + slug(en)
            i = 2
            while home in taken or home in new:
                home = "lumen_%s_%d" % (slug(en), i)
                i += 1
            new[home] = {"en": d[ks[0]]["en"], "tr": d[ks[0]]["tr"]}
        for u, n in ks:
            if (u, n) == (MODULE, home):
                continue
            set_raw(os.path.join(ROOT, u, "res", "values", d[(u, n)]["file"]), n, "@string/" + home)
            for loc in LOCALES:
                f = units[u].get(loc, {}).get(n)
                if f:
                    drop(os.path.join(ROOT, u, "res", "values-" + loc, f[0]), n)
            aliased.add(u)
            n_alias += 1
            if u in GEN:
                lang.setdefault("%s/%s" % (GEN[u], d[(u, n)]["file"]), set()).add(n)
    add_module_texts(new)
    for section, names in sorted(lang.items()):
        lang_drop(section, names)
    add_module(recs, aliased)
    if new:
        lang_add(new)
    print("share: apply: %d new module texts, %d places now aliases in %d units" % (len(new), n_alias, len(aliased)))
    return 0


def lang_add(new):
    """The translations of NEW module texts into section @strings/lumen_strings.xml of apps/i18n/langs/*.txt."""
    sys.path.insert(0, os.path.join(ROOT, "apps/i18n"))
    import gen
    for loc, dirs in gen.LOCALES.items():
        p = os.path.join(ROOT, "apps/i18n/langs", loc + ".txt")
        lines = open(p, encoding="utf-8").read().split("\n")
        at = lines.index("@strings/lumen_strings.xml") + 1
        end = next((i for i in range(at, len(lines)) if lines[i].startswith("@")), len(lines))
        rows = {l.split("=", 1)[0]: l for l in lines[at:end] if "=" in l}
        for k, v in new.items():
            t = v["tr"][dirs[0][len("values-"):]]
            rows[k] = "%s=%s" % (k, gen.unescape_android(re.sub(r"&lt;", "<", re.sub(r"&gt;", ">", re.sub(
                r"&amp;", "&", t)))))
        body = [rows[k] for k in sorted(rows)]
        tail = lines[end:] if end < len(lines) else [""]
        open(p, "w", encoding="utf-8").write("\n".join(lines[:at] + body + tail))


def main(argv):
    cmds = {"check": cmd_check, "report": cmd_report, "apply": cmd_apply, "known": cmd_known}
    if not argv or argv[0] not in cmds:
        print(__doc__)
        return 2
    return cmds[argv[0]]()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
