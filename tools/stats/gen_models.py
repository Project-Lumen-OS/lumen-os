"""The device registry table of the statistics client: apps/core/lumen-stats/src/org/lumen/stats/Models.java maps
ro.boot.xgimi.modelname to the registry codename (devices/<codename>/device.conf, tools/devices/devices.py), so every
projector reports the same model name on every image (the X50 and the RS30 report the Z9X's ro.product.device).
    python3 tools/stats/gen_models.py --check     exit 1 when Models.java is not the registry's
    python3 tools/stats/gen_models.py --write     write it
"""
import os
import sys

GSI = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(GSI, "apps", "core", "lumen-stats", "src", "org", "lumen", "stats", "Models.java")
sys.path.insert(0, os.path.join(GSI, "tools", "devices"))
import devices  # noqa: E402


def table(root=GSI):
    """{modelname: codename} of every supported device; a modelname in two entries is an error."""
    out = {}
    for code, e in sorted(devices.load(root).items()):
        for m in e["models"]:
            if m in out and out[m] != code:
                raise SystemExit("gen_models: %s is in %s and %s" % (m, out[m], code))
            out[m] = code
    return out


def java(t):
    rows = "".join('            case "%s": return "%s";\n' % (m, c) for m, c in sorted(t.items()))
    return ("// SPDX-License-Identifier: Apache-2.0\n"
            "// Generated by tools/stats/gen_models.py from devices/*/device.conf: do not edit.\n"
            "package org.lumen.stats;\n\n"
            "/** The device registry for the statistics client: ro.boot.xgimi.modelname -> Lumen codename. */\n"
            "final class Models {\n"
            "    private Models() {}\n\n"
            "    /** The codename of an XGIMI model, \"\" when the registry has no such model. */\n"
            "    static String codename(String xgimiModel) {\n"
            "        switch (xgimiModel == null ? \"\" : xgimiModel.trim()) {\n"
            + rows +
            "            default: return \"\";\n"
            "        }\n"
            "    }\n"
            "}\n")


def main():
    want = java(table())
    if sys.argv[1:] == ["--write"]:
        with open(OUT, "w") as f:
            f.write(want)
        print("gen_models: wrote %s" % os.path.relpath(OUT, GSI))
        return 0
    if sys.argv[1:] == ["--check"]:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != want:
            print("gen_models: %s is not the registry's (run --write)" % os.path.relpath(OUT, GSI))
            return 1
        print("gen_models: Models.java = registry (%d models)" % len(table()))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
