"""The device registry table of the statistics client: apps/core/lumen-stats/src/org/lumen/stats/Models.java maps
ro.boot.xgimi.modelname to the registry codename (devices/<codename>/device.conf, tools/devices/devices.py), so every
projector reports the same model name on every image (the X50 and the RS30 report the Z9X's ro.product.device).
The same registry also feeds the statistics server (tools/stats/server/lumen_stats.py FAMILIES and NAMES: it runs
without a checkout) and the download counter (tools/stats/github_downloads.py DEVICES: the release tag prefix of each
model's build.conf), each as a generated block between marker lines.
    python3 tools/stats/gen_models.py --check     exit 1 when one of the three is not the registry's
    python3 tools/stats/gen_models.py --write     write them
"""
import os
import re
import sys

GSI = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(GSI, "apps", "core", "lumen-stats", "src", "org", "lumen", "stats", "Models.java")
sys.path.insert(0, os.path.join(GSI, "tools", "devices"))
sys.path.insert(0, os.path.join(GSI, "tools", "ota"))
import devices  # noqa: E402
import licences  # noqa: E402


def table(root=GSI):
    """{modelname: codename} of every supported device; a modelname in two entries is an error."""
    out = {}
    for code, e in sorted(devices.load(root).items()):
        for m in e["models"]:
            if m in out and out[m] != code:
                raise SystemExit("gen_models: %s is in %s and %s" % (m, out[m], code))
            out[m] = code
    return out


def java(t):
    rows = "".join('            case "%s": return "%s";\n' % (m, c) for m, c in sorted(t.items()))
    return ("// Generated by tools/stats/gen_models.py from devices/*/device.conf: do not edit.\n"
            "package org.lumen.stats;\n\n"
            "/** The device registry for the statistics client: ro.boot.xgimi.modelname -> Lumen codename. */\n"
            "final class Models {\n"
            "    private Models() {}\n\n"
            "    /** The codename of an XGIMI model, \"\" when the registry has no such model. */\n"
            "    static String codename(String xgimiModel) {\n"
            "        switch (xgimiModel == null ? \"\" : xgimiModel.trim()) {\n"
            + rows +
            "            default: return \"\";\n"
            "        }\n"
            "    }\n"
            "}\n")


SERVER = os.path.join(GSI, "tools", "stats", "server", "lumen_stats.py")
DOWNLOADS = os.path.join(GSI, "tools", "stats", "github_downloads.py")
BEGIN, END = "# BEGIN GENERATED by tools/stats/gen_models.py from the device registry: do not edit\n", "# END GENERATED\n"
# release tag prefixes no build.conf names any more: the Installer, the HB before 1.0.8 (z9x-hb), Play 6 and the Z9X up
# to 1.0.7 (v<version>)
LEGACY_TAGS = [("lumen-installer", "installer"), ("z9x-hb", "goat_elegant"), ("play6", "dragon_healthy"), ("v", "horse_popular")]


def server_block(root=GSI):
    """FAMILIES (ro.product.device -> {model: codename}) and NAMES of the statistics server (it has no checkout)."""
    fam, names = {}, {}
    for code, e in sorted(devices.load(root).items()):
        for m in e["models"]:
            fam.setdefault(devices.family(e), {})[m] = code
        names[code] = e["name"]
    return ("FAMILIES = %s\nNAMES = %s\n" % (pformat(fam), pformat(names)))


def tag_prefixes(root=GSI):
    """[(release tag prefix, codename)] of every model with an image recipe (its build.conf tag), longest first."""
    sys.path.insert(0, os.path.join(root, "tools", "devices"))
    import layered  # noqa: E402
    out = set(LEGACY_TAGS)
    for code, e in devices.load(root).items():
        if e.get("image") == "none":
            continue
        b = layered.effective(os.path.join(root, "devices", code, "build.conf"))
        p = re.sub(r"\{([A-Z][A-Z0-9_]*)\}", lambda m: b.get("var." + m.group(1), m.group(0)), b["tag"].split("-{v}")[0])
        if re.fullmatch(r"[a-z0-9][a-z0-9-]*", p):   # a tag of the bare version ({v}: Play 6) has no prefix of its own
            out.add((p, code))
    return sorted(out, key=lambda r: (-len(r[0]), r))


def downloads_block(root=GSI):
    rows = ", ".join("(%r, %r)" % r for r in tag_prefixes(root))
    return "DEVICES = [%s]\n" % rows.replace("'", '"')


def pformat(d):
    import json
    return json.dumps(d, indent=4, sort_keys=True)


def spliced(path, block):
    """PATH with the text between its BEGIN and END marker lines replaced by BLOCK."""
    s = open(path, encoding="utf-8").read()
    a, b = s.find(BEGIN), s.find(END)
    if a < 0 or b < a:
        raise SystemExit("gen_models: %s has no generated block (%r ... %r)" % (os.path.relpath(path, GSI), BEGIN, END))
    return s[:a + len(BEGIN)] + block + s[b:]


def main():
    want = {OUT: java(table()), SERVER: spliced(SERVER, server_block()), DOWNLOADS: spliced(DOWNLOADS, downloads_block())}
    if sys.argv[1:] == ["--write"]:
        for path, text in want.items():
            with open(path, "w") as f:
                f.write(licences.generated(os.path.relpath(path, GSI), text))
            print("gen_models: wrote %s" % os.path.relpath(path, GSI))
        return 0
    if sys.argv[1:] == ["--check"]:
        bad = [p for p, text in want.items()
               if not licences.current(os.path.relpath(p, GSI), open(p).read() if os.path.exists(p) else None, text)]
        for p in bad:
            print("gen_models: %s is not the registry's (run --write)" % os.path.relpath(p, GSI))
        if bad:
            return 1
        print("gen_models: Models.java, lumen_stats.py and github_downloads.py = registry (%d models)" % len(table()))
        return 0
    print(__doc__)
    return 2

if __name__ == "__main__":
    sys.exit(main())
