#!/usr/bin/env python3
"""model_props.py: the stock model properties of one Lumen image, set by an init rc at early-init (one loader, the
data per model in devices/<c>/image/<x>_model_props.tsv and its prop files).

The stock XGIMI /system/bin/init (the string "/vendor/etc/xgimimodelname/" next to ro.boot.xgimi.modelname in the
stock dumps) loads /vendor/etc/xgimimodelname/<model>/build.prop at every boot; LineageOS init does not. An image that
serves several model codes or vendor firmwares cannot append one such file to its build.prop, so <x>_model_props.rc
sets the lines at early-init (init builtins only, before the vendor HWC and every other service starts), one block per
(model, firmware) whose stock file the dumps have, keyed on ro.boot.xgimi.modelname (kernel command line) and
ro.vendor.build.version.incremental (the vendor build.prop). A unit on another firmware gets no block. The vendor is
never written.

Table <x>_model_props.tsv, one row per model code and vendor firmware, tab separated:
  model  firmware  prop file  stock sha256  dump  lines
  dump   the name of the stock dump that has the file (given to check as NAME=PATH)
  lines  rule: every line x50_props.model_rule keeps (all but the identity keys, persist.sys.* and the first-start
               keys), in the stock order (the X50, RS30 and Titan images append the same lines to build.prop)
         read: only the rule's lines a Lumen image has a reader for, in the stock order, each one right below a
               '# read by ' comment that names the reader
Lines of the table that start with '## ' are the model's notes: they go into the header of the generated rc.

  model_props.py rc    DIR TABLE                  print the rc that DIR/TABLE and its prop files make
  model_props.py check DIR TABLE NAME=PATH...     on the build host: each stock file of the table has its pinned
                                                  sha256 (PATH/vendor/etc/xgimimodelname/<model>/build.prop, or
                                                  PATH/vendor_a/...), each prop file is the lines its row says, and
                                                  DIR/<x>_model_props.rc is the rc the table makes
DIR holds the table, the prop files, the rc and x50_props.py (flat in a recipe's input folder; in the repository the
rule is read from devices/g0111/image). Standard library only.
"""
import hashlib
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = re.compile(r"^([a-z0-9]+)_model_props\.tsv$")
MODEL = re.compile(r"^[A-Z][0-9A-Z]{4}$")
FIRMWARE = re.compile(r"^v[0-9]+\.[0-9]+\.[0-9]+$")
DUMP = re.compile(r"^[A-Z][A-Z0-9]*$")
LINES = ("rule", "read")
READ_BY = "# read by "
# a value init takes as one token: no space, no quote, no backslash, no $, no comment sign
VALUE = re.compile(r"^[A-Za-z0-9_.:/+,@=-]+$")
HEADER = """# SPDX-License-Identifier: Apache-2.0
# GENERATED by tools/devices/model_props.py rc from %s: do not edit by hand.
# The stock model properties. The stock XGIMI init loads /vendor/etc/xgimimodelname/<model>/build.prop at every boot,
# LineageOS init does not. Each block below sets the lines of one stock file at early-init, before the vendor HWC and
# every other service starts, only on the model and vendor firmware whose file it is. Init builtins only; the vendor
# is not changed."""


def die(msg):
    print("model_props: ERROR " + msg, file=sys.stderr)
    sys.exit(1)


def rule():
    for d in (HERE, os.path.join(HERE, "..", "..", "devices", "g0111", "image")):
        if os.path.isfile(os.path.join(d, "x50_props.py")):
            sys.path.insert(0, d)
            import x50_props
            return x50_props
    die("x50_props.py (the model prop rule) not found")


def prefix(name):
    m = TABLE.match(name)
    if not m:
        die("%s: a table is named <x>_model_props.tsv" % name)
    return m.group(1)


def rc_name(name):
    return prefix(name) + "_model_props.rc"


def notes(d, name):
    return [l.rstrip("\n")[3:] for l in open(os.path.join(d, name), encoding="utf-8") if l.startswith("## ")]


def table(d, name):
    """[(model, firmware, prop file, stock sha256, dump, lines)] in the table's order"""
    rows = []
    seen = set()
    pre = prefix(name)
    for n, raw in enumerate(open(os.path.join(d, name), encoding="utf-8"), 1):
        line = raw.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) != 6:
            die("%s:%d: want 6 tab-separated fields" % (name, n))
        model, fw, props, sha, dump, lines = f
        if not MODEL.match(model) or not FIRMWARE.match(fw) or not re.match(r"^[0-9a-f]{64}$", sha) \
                or not DUMP.match(dump) or lines not in LINES \
                or not re.match(r"^%s_model_prop_[a-z0-9]+\.txt$" % re.escape(pre), props):
            die("%s:%d: bad row %r" % (name, n, line))
        if (model, fw) in seen:
            die("%s:%d: %s %s twice" % (name, n, model, fw))
        seen.add((model, fw))
        rows.append((model, fw, props, sha, dump, lines))
    if not rows:
        die(name + ": empty table")
    return rows


def props(d, name, lines="rule"):
    """the KEY=VALUE lines of a prop file, each one init can set and the rule keeps (read: each below its reader)"""
    x = rule()
    out = []
    reader = False
    for n, raw in enumerate(open(os.path.join(d, name), encoding="utf-8"), 1):
        line = raw.rstrip("\n")
        if not line.strip():
            reader = False
            continue
        if line.startswith("#"):
            reader = reader or (line.startswith(READ_BY) and len(line) > len(READ_BY))
            continue
        k, eq, v = line.partition("=")
        if not eq or not x.KEY.match(k) or not VALUE.match(v):
            die("%s:%d: not KEY=VALUE init can set: %r" % (name, n, line))
        if not x.model_rule(line):
            die("%s:%d: %s is a key the model rule leaves out" % (name, n, k))
        if lines == "read" and not reader:
            die("%s:%d: %s has no '%s' comment right above it" % (name, n, k, READ_BY.strip()))
        reader = False
        out.append((k, v))
    if not out:
        die(name + ": no props")
    return out


def make_rc(d, name):
    blocks = [HEADER % name] + ["# " + l for l in notes(d, name)]
    for model, fw, pf, sha, _, lines in table(d, name):
        blocks.append("\n# %s on %s: %s (stock sha256 %s)" % (model, fw, pf, sha))
        blocks.append("on early-init && property:ro.boot.xgimi.modelname=%s && property:ro.vendor.build.version.incremental=%s"
                      % (model, fw))
        blocks += ["    setprop %s %s" % kv for kv in props(d, pf, lines)]
    return "\n".join(blocks) + "\n"


def stock_file(root, model):
    for v in ("vendor", "vendor_a"):
        p = os.path.join(root, v, "etc", "xgimimodelname", model, "build.prop")
        if os.path.isfile(p):
            return p
    return None


def in_order(have, want):
    """have is want with lines left out, the order kept"""
    i = 0
    for h in have:
        while i < len(want) and want[i] != h:
            i += 1
        if i == len(want):
            return False
        i += 1
    return True


def check(d, name, dumps):
    x = rule()
    bad = 0
    rows = table(d, name)
    for model, fw, pf, sha, dump, lines in rows:
        if dump not in dumps:
            print("model_props: ERROR %s %s: dump %s not given" % (model, fw, dump)); bad = 1; continue
        stock = stock_file(dumps[dump], model)
        if not stock:
            print("model_props: ERROR %s %s: no stock file under %s" % (model, fw, dumps[dump])); bad = 1; continue
        raw = open(stock, "rb").read()
        if hashlib.sha256(raw).hexdigest() != sha:
            print("model_props: ERROR %s %s: %s is not the pinned stock file" % (model, fw, stock)); bad = 1; continue
        want = [l.strip() for l in raw.decode("utf-8", "replace").split("\n") if x.model_rule(l.strip())]
        have = ["%s=%s" % kv for kv in props(d, pf, lines)]
        if lines == "rule" and have != want:
            print("model_props: ERROR %s is not the rule's lines of the %s %s stock file" % (pf, model, fw)); bad = 1
        if lines == "read" and not in_order(have, want):
            print("model_props: ERROR %s is not a choice of the rule's lines of the %s %s stock file in its order"
                  % (pf, model, fw)); bad = 1
    rc = rc_name(name)
    if open(os.path.join(d, rc), encoding="utf-8").read() != make_rc(d, name):
        print("model_props: ERROR %s is not the rc %s makes (run: model_props.py rc)" % (rc, name)); bad = 1
    if not bad:
        print("model_props: %s: %d model / firmware blocks, every prop file = its stock file by its row"
              % (name, len(rows)))
    return bad


def main(a):
    if len(a) == 3 and a[0] == "rc":
        sys.stdout.write(make_rc(a[1], a[2]))
        return 0
    if len(a) >= 4 and a[0] == "check" and all("=" in s for s in a[3:]):
        return check(a[1], a[2], dict(s.split("=", 1) for s in a[3:]))
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
