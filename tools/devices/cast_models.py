"""cast_models.py: screen casting is ONE shared feature on every model (2026-11-21). Checks the rule on the
tree and writes the model table the casting screen reads.

  cast_models.py [--root DIR] check     the rule below and the table in the AirPlay app is current (exit 1 = red)
  cast_models.py [--root DIR] write     write apps/LumenAirPlay/assets/cast/models.tsv from the device data
  cast_models.py [--root DIR] table     print the table

The rule, for every device with an image recipe (devices/<c>/build.conf):
  - devices/<c>/cast.conf exists, says airplay=1 and miracast=1 and mirror_4k=0|1 (no other key);
  - the recipe's apps= ship the AirPlay receiver with the casting screen (Z9xAirPlay), the Miracast sink
    (LumenMiracast) and its Wi-Fi Direct TV device type (LumenWifiP2pOverlay);
  - the recipe's overlays= carry the sink's privileged and default permission files;
  - the recipe's prebuilt= carries Lumen Play, the DLNA renderer the casting screen explains;
  - the menu profile (devices/<c>/menu.json) names the quick menu tile "mirroring" and the All settings row
    "settings.casting".
The table: model code, codename, ABI and mirror_4k per model code of device.conf models= (sorted by code).
"""
import argparse
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import menu_layers  # noqa: E402


KEYS = ("airplay", "miracast", "mirror_4k")
APPS = ("Z9xAirPlay", "LumenMiracast", "LumenWifiP2pOverlay")
OVERLAYS = ("overlay/v1/privapp-permissions-lumen-miracast.xml", "overlay/v1/lumen-miracast-default-permissions.xml")
FEATURES = ("mirroring", "settings.casting")
TABLE = "apps/LumenAirPlay/assets/cast/models.tsv"
HEADER = "# model\tcodename\tabi\tmirror_4k  (generated by tools/devices/cast_models.py write, do not edit)\n"


def conf(path):
    if os.path.basename(path) in ("build.conf", "device.conf"):
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import layered
        return layered.effective(path)
    out = {}
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            k, sep, v = line.partition("=")
            if not sep:
                raise ValueError("%s: not key=value: %r" % (path, line))
            out[k.strip()] = v.strip()
    return out


def devices(root):
    top = os.path.join(root, "devices")
    return sorted(c for c in os.listdir(top)
                  if not c.startswith(("_", ".")) and os.path.isfile(os.path.join(top, c, "build.conf")))


def problems(root):
    bad = []
    for c in devices(root):
        d = os.path.join(root, "devices", c)
        # the model's own cast.conf, else its family's (tools/devices/layered.py: one file for a family that has the same)
        sys.path.insert(0, os.path.join(root, "tools", "devices"))
        import layered
        cp = layered.find(os.path.join(d, "build.conf"), "cast.conf") or os.path.join(d, "cast.conf")
        if not os.path.isfile(cp):
            bad.append("%s: no cast.conf (screen casting is on every model)" % c)
            continue
        cc = conf(cp)
        extra = sorted(set(cc) - set(KEYS))
        if extra:
            bad.append("%s: cast.conf has unknown keys %s" % (c, ", ".join(extra)))
        for k in ("airplay", "miracast"):
            if cc.get(k) != "1":
                bad.append("%s: cast.conf %s=%s, every model has every receiver" % (c, k, cc.get(k)))
        if cc.get("mirror_4k") not in ("0", "1"):
            bad.append("%s: cast.conf mirror_4k must be 0 or 1" % c)
        bc = conf(os.path.join(d, "build.conf"))
        apps = bc.get("apps", "").split()
        for a in APPS:
            if a not in apps:
                bad.append("%s: build.conf apps= lacks %s" % (c, a))
        # DLNA: Lumen Play is the renderer of every image (its published APK, devices/_image/prebuilt.tsv); the casting
        # screen explains it, so a model without it would show a card for a receiver it lacks
        if "LumenPlay" not in bc.get("prebuilt", "").split():
            bad.append("%s: build.conf prebuilt= lacks LumenPlay (the DLNA renderer of the casting screen)" % c)
        ov = bc.get("overlays", "").split()
        for o in OVERLAYS:
            if o not in ov:
                bad.append("%s: build.conf overlays= lacks %s" % (c, o))
        mp = os.path.join(d, "menu.json")
        feats = menu_layers.effective(mp).get("features", {}) if os.path.isfile(mp) else {}
        for f in FEATURES:
            if f not in feats:
                bad.append("%s: menu.json features lack %s" % (c, f))
    return bad


def table(root):
    rows = []
    for c in devices(root):
        d = os.path.join(root, "devices", c)
        import layered
        dc, cc = conf(os.path.join(d, "device.conf")), conf(layered.find(os.path.join(d, "build.conf"), "cast.conf") or os.path.join(d, "cast.conf"))
        for m in dc.get("models", "").split():
            rows.append((m, c, dc.get("abi", ""), cc.get("mirror_4k", "0")))
    return HEADER + "".join("\t".join(r) + "\n" for r in sorted(rows))


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    ap.add_argument("cmd", choices=("check", "write", "table"))
    a = ap.parse_args(argv)
    if a.cmd == "table":
        sys.stdout.write(table(a.root))
        return 0
    if a.cmd == "write":
        p = os.path.join(a.root, TABLE)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(table(a.root))
        print("cast_models: wrote " + TABLE)
        return 0
    bad = problems(a.root)
    p = os.path.join(a.root, TABLE)
    if not os.path.isfile(p) or open(p, encoding="utf-8").read() != table(a.root):
        bad.append("%s is not current: run tools/devices/cast_models.py write" % TABLE)
    for b in bad:
        print("cast_models: " + b)
    print("cast_models: %s, %d devices" % ("RED" if bad else "OK", len(devices(a.root))))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
