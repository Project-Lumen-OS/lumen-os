#!/usr/bin/env python3
"""gen_icons.py: the Lumen icon set (apps/core/lumen-icons) from Material Symbols, the official Google source.

  gen_icons.py write [--cache DIR]     fetch the pinned SVGs, write res/drawable/lumen_ic_*.xml, record each SVG's
                                       sha256 in tools/icons/icons.tsv (a recorded sha256 that differs is red)
  gen_icons.py check [--cache DIR]     the committed drawables equal a fresh conversion of the pinned SVGs
  gen_icons.py check --offline         no network: every table row has its drawable with the pin and the recorded
                                       sha256 in its header, its path data parses, no drawable without a row

Source: github.com/google/material-design-icons at PIN, symbols/web/<name>/materialsymbolsrounded/<name>[_fill1]_24px.svg
(Material Symbols Rounded, weight 400, grade 0, optical size 24; Apache License 2.0, LICENSE of that repository).
A drawable is a 24 dp VectorDrawable over the SVG's own 960 unit box, white, tinted by @color/lumen_icon_tint so
its colour follows the view state (focused, disabled) the way the Lumen rows draw their text. Arrows and chevrons that
point along the reading direction mirror in a right to left UI; the remote key arrows never do (the key is where it is).
"""
import hashlib
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
GSI = os.path.dirname(os.path.dirname(HERE))
TABLE = os.path.join(HERE, "icons.tsv")
OUT = os.path.join(GSI, "apps", "core", "lumen-icons", "res", "drawable")
REPO = "google/material-design-icons"
PIN = "10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7"
URL = "https://raw.githubusercontent.com/%s/%s/symbols/web/%s/materialsymbolsrounded/%s%s_24px.svg"
MIRRORED = {"chevron_right", "chevron_left", "arrow_forward", "arrow_back"}
PATH_OK = re.compile(r"^[MmZzLlHhVvCcSsQqTtAa0-9.,\- ]+$")


def rows():
    out = []
    for line in open(TABLE, encoding="utf-8"):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) != 5 or f[2] not in ("0", "1"):
            raise SystemExit("icons.tsv: bad row %r" % line)
        out.append({"name": f[0], "material": f[1], "fill": f[2], "sha": f[3], "meaning": f[4]})
    names = [r["name"] for r in out]
    if len(set(names)) != len(names):
        raise SystemExit("icons.tsv: a name is used twice")
    sources = [(r["material"], r["fill"]) for r in out]
    if len(set(sources)) != len(sources):
        raise SystemExit("icons.tsv: two names draw the same source icon")
    return out


def fetch(r, cache):
    fn = "%s%s_24px.svg" % (r["material"], "_fill1" if r["fill"] == "1" else "")
    local = os.path.join(cache, PIN, fn) if cache else None
    if local and os.path.isfile(local):
        return open(local, "rb").read()
    url = URL % (REPO, PIN, r["material"], r["material"], "_fill1" if r["fill"] == "1" else "")
    try:
        data = urllib.request.urlopen(url, timeout=30).read()
    except urllib.error.URLError:   # a Python without CA certificates (python.org build on macOS): curl has them
        data = subprocess.run(["curl", "-fsSL", "-m", "30", url], check=True, stdout=subprocess.PIPE).stdout
    if local:
        os.makedirs(os.path.dirname(local), exist_ok=True)
        with open(local, "wb") as f:
            f.write(data)
    return data


def path_of(svg):
    s = svg.decode("utf-8")
    if 'viewBox="0 -960 960 960"' not in s:
        raise ValueError("not a Material Symbols 960 unit SVG")
    ds = re.findall(r'<path d="([^"]+)"', s)
    if len(ds) != 1 or not PATH_OK.match(ds[0]):
        raise ValueError("expected one plain path")
    return ds[0]


def drawable(r, sha, d):
    mirror = '\n    android:autoMirrored="true"' if r["name"] in MIRRORED else ""
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Material Symbols Rounded "%s" (weight 400, fill %s), %s at %s, Apache License 2.0.\n'
            '     Source SVG sha256 %s. Generated by tools/icons/gen_icons.py, do not edit. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n'
            '    android:height="24dp"\n'
            '    android:viewportWidth="960"\n'
            '    android:viewportHeight="960"%s\n'
            '    android:tint="@color/lumen_icon_tint">\n'
            '    <group android:translateY="960">\n'
            '        <path\n'
            '            android:fillColor="@android:color/white"\n'
            '            android:pathData="%s" />\n'
            '    </group>\n'
            '</vector>\n') % (r["material"], r["fill"], REPO, PIN, sha, mirror, d)


def out_path(r):
    return os.path.join(OUT, "lumen_ic_%s.xml" % r["name"])


def write_table(rs):
    head = [l for l in open(TABLE, encoding="utf-8") if l.startswith("#") or not l.strip()]
    with open(TABLE, "w", encoding="utf-8") as f:
        f.writelines(head)
        for r in rs:
            f.write("\t".join([r["name"], r["material"], r["fill"], r["sha"], r["meaning"]]) + "\n")


def offline(rs):
    errs = []
    want = {os.path.basename(out_path(r)) for r in rs}
    have = {n for n in os.listdir(OUT) if n.startswith("lumen_ic_")} if os.path.isdir(OUT) else set()
    for extra in sorted(have - want):
        errs.append("%s has no row in icons.tsv" % extra)
    for r in rs:
        p = out_path(r)
        if not os.path.isfile(p):
            errs.append("missing %s" % os.path.relpath(p, GSI))
            continue
        t = open(p, encoding="utf-8").read()
        if r["sha"] == "-" or ("sha256 %s" % r["sha"]) not in t or PIN not in t:
            errs.append("%s: header does not name the pin and the recorded sha256" % os.path.basename(p))
        m = re.search(r'android:pathData="([^"]+)"', t)
        if not m or not PATH_OK.match(m.group(1)):
            errs.append("%s: no plain path data" % os.path.basename(p))
        if '"%s"' % r["material"] not in t or ("fill %s)" % r["fill"]) not in t:
            errs.append("%s: header names another source icon" % os.path.basename(p))
        if (r["name"] in MIRRORED) != ("autoMirrored" in t):
            errs.append("%s: autoMirrored does not match the rule" % os.path.basename(p))
    return errs


def main(argv):
    if not argv or argv[0] not in ("write", "check"):
        print(__doc__)
        return 2
    cache = None
    if "--cache" in argv:
        cache = argv[argv.index("--cache") + 1]
    rs = rows()
    if argv[0] == "check" and "--offline" in argv:
        errs = offline(rs)
    else:
        errs = []
        os.makedirs(OUT, exist_ok=True)
        for r in rs:
            svg = fetch(r, cache)
            sha = hashlib.sha256(svg).hexdigest()
            if r["sha"] not in ("-", sha):
                errs.append("%s: source sha256 %s, recorded %s" % (r["name"], sha, r["sha"]))
                continue
            text = drawable(r, sha, path_of(svg))
            if argv[0] == "write":
                r["sha"] = sha
                with open(out_path(r), "w", encoding="utf-8") as f:
                    f.write(text)
            elif not os.path.isfile(out_path(r)) or open(out_path(r), encoding="utf-8").read() != text:
                errs.append("%s differs from a fresh conversion" % os.path.basename(out_path(r)))
        if argv[0] == "write" and not errs:
            write_table(rs)
            errs = offline(rs)
    for e in errs:
        print("gen_icons: " + e)
    print("gen_icons: %s %d icons" % ("RED" if errs else "OK", len(rs)))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
