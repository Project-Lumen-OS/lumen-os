#!/usr/bin/env python3
"""gen_codes.py: the gmpf AIDL code tables of every AIDL projector from one shared base and a delta per model
(lumen-hal tables phase 3, tools/arch/README.md).

The XGIMI gmpf AIDL HAL is the same release line on the HB (G0130), the X50 (G0111) and the next models: 1,158 rows of
the two full tables were identical, the X50 adds 40 methods and one proxy signature differs. Each model's full table
(the hal_codes file of its registry entry, read by check_aidl_hal.py, the app tests and the image verifiers) is now
GENERATED from:

  devices/_hal/gmpf-aidl/base.tsv     the rows the models share (comments, then "# service<TAB>code<TAB>...", rows)
  devices/<codename>/hal/codes.delta.tsv
      head<TAB>TEXT                   a comment line that starts the model's table (TEXT verbatim)
      +<TAB>ROW                       a row of that model: added, or replacing the base row of the same service + code
      -<TAB>SERVICE<TAB>CODE          a base row the model does not have
      # ...                           comments of the delta file (not copied)

Output: the head lines, the base header line, then every row sorted by service and numeric code (the order of the
stock-dump generators). A new AIDL model is one delta file (RS30: X50 + 29 codes).

  gen_codes.py [--check]              every device with a delta: regenerate its hal_codes file, or (--check, the
                                      default) compare byte for byte and exit 1 on a difference
  gen_codes.py --write                write the generated tables
  gen_codes.py bootstrap OUT_DIR      derive base.tsv and the deltas from the current full tables (how the split was
                                      made; writes only under OUT_DIR)
Exit 0 green, 1 red, 2 usage.
"""
import os
import sys

sys.dont_write_bytecode = True
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "devices"))
import devices  # noqa: E402

BASE = "devices/_hal/gmpf-aidl/base.tsv"
HEADER = "# service\tcode\tmethod\tsignature\tndk_proxy_args\tkind\tsource"


def key(row):
    f = row.split("\t")
    return (f[0], int(f[1]))


def read_table(path):
    """(head comment lines, rows) of a full table or of base.tsv (the head of base.tsv is its own documentation)."""
    head, rows, seen_header = [], [], False
    for line in open(path, encoding="utf-8").read().split("\n"):
        if not line:
            continue
        if line == HEADER:
            seen_header = True
            continue
        if line.startswith("#"):
            if not seen_header:
                head.append(line)
            continue
        rows.append(line)
    if not seen_header:
        raise ValueError("%s: no header line %r" % (path, HEADER))
    return head, rows


def aidl_devices():
    """[(codename, hal_codes path, delta path)] of every registry device with a codes delta."""
    out = []
    for c, d in sorted(devices.load(ROOT).items()):
        delta = os.path.join(ROOT, "devices", c, "hal", "codes.delta.tsv")
        if os.path.isfile(delta):
            hc = d.get("hal_codes", "")
            if not hc or hc == "none":
                raise ValueError("devices/%s has hal/codes.delta.tsv but no hal_codes in device.conf" % c)
            out.append((c, os.path.join(ROOT, "devices", c, hc) if not hc.startswith("devices/") else os.path.join(ROOT, hc),
                        delta))
    return out


def generate(base_rows, delta_path):
    head, rows = [], {key(r): r for r in base_rows}
    for n, line in enumerate(open(delta_path, encoding="utf-8").read().split("\n"), 1):
        if not line or line.startswith("#"):
            continue
        tag, _, rest = line.partition("\t")
        if tag == "head":
            head.append(rest)
        elif tag == "+":
            rows[key(rest)] = rest
        elif tag == "-":
            k = (rest.split("\t")[0], int(rest.split("\t")[1]))
            if k not in rows:
                raise ValueError("%s:%d: removes %s %d, which the base lacks" % (delta_path, n, k[0], k[1]))
            del rows[k]
        else:
            raise ValueError("%s:%d: cannot read %r" % (delta_path, n, line))
    return "".join(x + "\n" for x in head + [HEADER] + [rows[k] for k in sorted(rows)])


def bootstrap(out_dir):
    tables = {}
    for c, path, _ in aidl_devices_or_registry():
        tables[c] = (path, read_table(path))
    sets = [set(rows) for _, (_, rows) in tables.values()]
    common = set.intersection(*sets) if sets else set()
    os.makedirs(os.path.join(out_dir, "devices/_hal/gmpf-aidl"), exist_ok=True)
    with open(os.path.join(out_dir, BASE), "w", encoding="utf-8") as f:
        f.write("# gmpf AIDL rows shared by every AIDL model (tools/hal/gen_codes.py), generated by gen_codes.py bootstrap\n")
        f.write("".join(x + "\n" for x in [HEADER] + sorted(common, key=key)))
    for c, (_, (head, rows)) in tables.items():
        d = os.path.join(out_dir, "devices", c, "hal")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "codes.delta.tsv"), "w", encoding="utf-8") as f:
            f.write("# %s: its gmpf AIDL rows beyond devices/_hal/gmpf-aidl/base.tsv (tools/hal/gen_codes.py)\n" % c)
            f.write("".join("head\t%s\n" % h for h in head))
            f.write("".join("+\t%s\n" % r for r in sorted(set(rows) - common, key=key)))
            base_keys = {key(r) for r in rows}
            f.write("".join("-\t%s\t%d\n" % k for k in sorted({key(r) for r in common} - base_keys)))
    print("gen_codes: bootstrap: %d shared rows; deltas for %s" % (len(common), " ".join(sorted(tables))))


def aidl_devices_or_registry():
    """bootstrap: every aidl-table device of the registry with its hal_codes file."""
    out = []
    for c, d in sorted(devices.load(ROOT).items()):
        if d.get("hal_check") == "aidl-table" and d.get("hal_codes", "none") != "none":
            hc = d["hal_codes"]
            out.append((c, os.path.join(ROOT, hc) if hc.startswith("devices/") else os.path.join(ROOT, "devices", c, hc), None))
    return out


def main(argv):
    if argv[:1] == ["bootstrap"] and len(argv) == 2:
        bootstrap(os.path.abspath(argv[1]))
        return 0
    if argv not in ([], ["--check"], ["--write"]):
        print(__doc__)
        return 2
    write = argv == ["--write"]
    try:
        _, base_rows = read_table(os.path.join(ROOT, BASE))
        devs = aidl_devices()
        bad = 0
        for c, path, delta in devs:
            body = generate(base_rows, delta)
            old = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
            rel = os.path.relpath(path, ROOT)
            if old == body:
                print("gen_codes: %s: %s = base + delta (%d rows)" % (c, rel, body.count("\n") - 1))
            elif write:
                open(path, "w", encoding="utf-8").write(body)
                print("gen_codes: %s: wrote %s" % (c, rel))
            else:
                print("gen_codes: %s: %s is NOT base + delta" % (c, rel))
                bad = 1
    except (ValueError, OSError, devices.RegistryError) as e:
        print("gen_codes: ERROR %s" % e)
        return 1
    if not devs:
        print("gen_codes: ERROR no device has devices/<codename>/hal/codes.delta.tsv")
        return 1
    return bad


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
