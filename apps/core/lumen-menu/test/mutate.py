def main():
    base = subprocess.run(["sh", os.path.join(HERE, "run.sh")], capture_output=True, text=True)
    if base.returncode != 0:
        print("the unmutated tree is red already: fix test/run.sh first")
        print(base.stdout[-2000:])
        sys.exit(2)
    killed, survived = 0, []
    prefix = sys.argv[1] if len(sys.argv) > 1 else ""     # a name prefix: the targeted mutants of one change
    only = os.environ.get("MUT_ONLY", "")
    for name, rel, old, new in MUTANTS:
        if not name.startswith(prefix):
            continue
        if only and not re.search(only, name):
            continue
        tmp = tempfile.mkdtemp(prefix="lumen_menu_mut.")
        try:
            root = os.path.join(tmp, "gsi")
            dst = os.path.join(root, "apps", "core", "lumen-menu")
            shutil.copytree(MOD, dst)
            os.makedirs(os.path.join(root, "devices"))
            for c in sorted(os.listdir(os.path.join(G, "devices"))):
                j = os.path.join(G, "devices", c, "menu.json")
                if os.path.isfile(j):
                    os.makedirs(os.path.join(root, "devices", c))
                    menu_layers.copy_profile(j, os.path.join(root, "devices", c, "menu.json"))
            # the focus page's remote table (FocusGuideTest)
            os.makedirs(os.path.join(root, "devices", "_remotes"))
            shutil.copy(os.path.join(G, "devices", "_remotes", "focus_guide.tsv"), os.path.join(root, "devices", "_remotes"))
            # the hotspot permission check reads every projector app's manifest
            for extra in ("devices/goat_elegant/app/HbProjector.manifest.diff", "tools/devices/patch_file.py"):   # not rel: the mutant's file
                os.makedirs(os.path.dirname(os.path.join(root, extra)), exist_ok=True)
                shutil.copy(os.path.join(G, extra), os.path.join(root, extra))
            for app in ("LumenProjector/core", "LumenProjector/host/activity"):   # the Play 6 manifest is model data now
                os.makedirs(os.path.join(root, "apps", app), exist_ok=True)
                shutil.copy(os.path.join(G, "apps", app, "AndroidManifest.xml"), os.path.join(root, "apps", app))
            # the adapters the profiles name and their *Rows sections (read by the contract test)
            for c in os.listdir(os.path.join(root, "devices")):
                if not os.path.isfile(os.path.join(root, "devices", c, "menu.json")):
                    continue
                ad = json.load(open(os.path.join(root, "devices", c, "menu.json"))).get("adapter", "")
                if ad and os.path.isfile(os.path.join(G, ad)):
                    d = os.path.dirname(ad)
                    os.makedirs(os.path.join(root, d), exist_ok=True)
                    for f in [ad] + glob.glob(os.path.join(G, d, "*Rows.java")):
                        shutil.copy(os.path.join(G, f), os.path.join(root, d))
            # the shared settings rows the Z9X-family adapters delegate to (MenuSpecTest.sections reads them too), else
            # every mutant is red on their rows and a mutant that the tests miss counts as killed
            rows = os.path.join("apps", "common", "projector", "src", "org", "lumen", "projector", "panel", "SettingsRows.java")
            if os.path.isfile(os.path.join(G, rows)):
                os.makedirs(os.path.dirname(os.path.join(root, rows)), exist_ok=True)
                shutil.copy(os.path.join(G, rows), os.path.join(root, rows))
            p = os.path.join(dst, rel)
            src = open(p, encoding="utf-8").read()
            if src.count(old) != 1:
                print("BROKEN mutant (pattern %d times): %s" % (src.count(old), name))
                survived.append(name)
                continue
            open(p, "w", encoding="utf-8").write(src.replace(old, new))
            r = subprocess.run(["sh", os.path.join(dst, "test", "run.sh")], capture_output=True, text=True)
            if r.returncode != 0:
                killed += 1
                why = next((l for l in r.stdout.splitlines() if l.startswith("FAIL")), "red")
                print("killed   %-45s %s" % (name, why[:110]))
            else:
                survived.append(name)
                print("SURVIVED %s" % name)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
    print("lumen-menu mutants: %d killed, %d survived" % (killed, len(survived)))
    sys.exit(0 if not survived else 1)


if __name__ == "__main__":
    main()
