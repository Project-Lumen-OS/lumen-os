"""Keyboard layouts of Lumen Keyboard as data (apps/LumenKeyboard/README.md).

  gen_layouts.py write    write res/xml/lumen_*.xml and put the language key into every AOSP letter and symbol page
  gen_layouts.py check    exit 1 when a file differs from what this table makes (run by test/run.sh)

Every page is as wide as the AOSP pages: four rows of 11 keys, then the bottom row mode, shift, language
(2 columns), space (5 columns), left, right. A letter row of 12 keys (ЙЦУКЕН: ъ, ї or the apostrophe after х) gets a
narrower gap so it ends where the others end; the key navigation goes by the keys' rectangles (KeyGrid).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
XML = os.path.join(os.path.dirname(HERE), "res", "xml")

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/LumenKeyboard/tools/gen_layouts.py from its table: edit the table, then run it with write. -->
"""
KB_OPEN = """<Keyboard xmlns:android="http://schemas.android.com/apk/res/android"
    android:keyHeight="@dimen/key_height"
    android:keyWidth="@dimen/key_width"
    android:verticalGap="@dimen/keyboard_vertical_gap"
    android:horizontalGap="@dimen/keyboard_horizontal_gap" >
"""

DIGITS = [("1", "@xml/shift_1"), ("2", "@xml/shift_2"), ("3", "@xml/shift_3"), ("4", "@xml/shift_4"),
          ("5", "@xml/shift_5"), ("6", "@xml/shift_6"), ("7", "@xml/shift_7"), ("8", "@xml/shift_8"),
          ("9", "@xml/shift_9"), ("0", "@xml/shift_0")]

# lang -> four rows of 11 keys (a letter row may have 12). A key is "x" or "x:yz" (long OK opens x, y, z, and the
# key shows y small in its corner). "#" in row 0 = the digit row. Rows follow the standard ЙЦУКЕН layouts, ё stays a
# long press on е as on Gboard for Android TV. The README lists every long-pressed letter (test/alphabet_check.py).
LAYOUTS = {
    "ru": ["#",
           "й ц у к е:ё н г ш щ з х ъ",
           "ф ы в а п р о л д ж э",
           "я ч с м и т ь б ю , ."],
    "uk": ["#",
           "й ц у к е н г:ґ ш щ з х ї",
           "ф і в а п р о л д ж є",
           "я ч с м и т ь б ю ' .:,?!"],
    "be": ["#",
           "й ц у к е:ё н г ш ў з х '",
           "ф ы в а п р о л д ж э",
           "я ч с м і т ь б ю , ."],
    # Kazakh: its nine letters and ё take the digit row (digits on a long press, as on the phone keyboards)
    "kk": ["ә:1 і:2 ң:3 ғ:4 ү:5 ұ:6 қ:7 ө:8 һ:9 ё:0",
           "й ц у к е н г ш щ з х ъ",
           "ф ы в а п р о л д ж э",
           "я ч с м и т ь б ю , ."],
    # Arabic PC layout without its two-letter key (لا), alef forms on a long press
    "ar": ["#",
           "ض ص ث ق ف غ ع ه خ ح ج",
           "ش س ي ب ل ا:أإآ ت ن م ك ط",
           "ذ ئ ء ؤ ر ى ة و ز ظ د"],
}
WIDE = 12

LANG_KEY = """        <Key
            android:codes="-9"
            android:keyIcon="@drawable/ic_ime_language"
            android:keyLabel="@string/keyboardview_keycode_language"
            android:keyWidth="@dimen/language_key_width" />
"""

BOTTOM = """    <Row android:rowEdgeFlags="bottom" >
        <Key
            android:codes="-2"
            android:keyEdgeFlags="left"
            android:keyLabel="@string/keyboardview_keycode_mode_change"
            android:keyIcon="@drawable/ic_ime_symbols" />
        <Key
            android:codes="-1"
            android:keyLabel="@string/keyboardview_keycode_shift"
            android:keyIcon="@drawable/ic_ime_shift_off" />
""" + LANG_KEY + """        <Key
            android:codes="32"
            android:keyIcon="@drawable/ic_ime_space"
            android:keyLabel="@string/keyboardview_keycode_space"
            android:keyWidth="@dimen/space_key_width" />
        <Key
            android:codes="-3"
            android:keyLabel="@string/keyboardview_keycode_left"
            android:keyIcon="@drawable/ic_ime_left_arrow" />
        <Key
            android:codes="-4"
            android:keyEdgeFlags="right"
            android:keyLabel="@string/keyboardview_keycode_right"
            android:keyIcon="@drawable/ic_ime_right_arrow" />
    </Row>
"""


def esc(ch):
    if ch in "@?#'\\":
        return "\\" + ch
    return {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;"}.get(ch, ch)


def key(code, label, popup=None, edge=None, icon=None, hint=None):
    s = '        <Key\n            android:codes="%d"\n' % code
    if edge:
        s += '            android:keyEdgeFlags="%s"\n' % edge
    if icon:
        s += '            android:keyIcon="%s"\n' % icon
    s += '            android:keyLabel="%s"' % label
    if hint:
        s += '\n            android:popupCharacters="%s"' % "".join(esc(c) for c in hint)
    if popup:
        s += '\n            android:popupKeyboard="%s"' % popup
    return s + " />\n"


def parse_row(row):
    out = []
    for tok in row.split():
        ch, _, more = tok.partition(":")
        if len(ch) != 1:
            raise SystemExit("gen_layouts: one character per key, got %r" % tok)
        out.append((ch, list(more)))
    return out


def popup_xml(chars):
    rows = "".join(key(ord(c), esc(c)) for c in chars)
    return HEADER + KB_OPEN + "    <Row>\n" + rows + "    </Row>\n</Keyboard>\n"


def layout_files(lang, rows):
    """{file name: text} of one language: its page and its long-press popups."""
    files = {}
    body = ""
    for r, row in enumerate(rows):
        n = len(parse_row(row)) if row != "#" else 0
        attrs = ' android:rowEdgeFlags="top"' if r == 0 else ""
        if n == WIDE:
            attrs += ' android:horizontalGap="@dimen/keyboard_horizontal_gap_12"'
        body += "    <Row%s>\n" % attrs
        if row == "#":
            keys = [key(ord(d), d, pop, "left" if i == 0 else None) for i, (d, pop) in enumerate(DIGITS)]
            keys.append(key(-5, "@string/keyboardview_keycode_delete", edge="right", icon="@drawable/ic_ime_delete"))
        else:
            parsed = parse_row(row)
            keys = []
            for i, (ch, more) in enumerate(parsed):
                pop = None
                if more:
                    name = "lumen_pop_%s_%d_%d" % (lang, r, i)
                    files[name + ".xml"] = popup_xml([ch] + more)
                    pop = "@xml/" + name
                edge = "left" if i == 0 else ("right" if i == len(parsed) - 1 and r else None)
                keys.append(key(ord(ch), esc(ch), pop, edge, hint=more))
            if r == 0:
                keys.append(key(-5, "@string/keyboardview_keycode_delete", edge="right", icon="@drawable/ic_ime_delete"))
        if len(keys) not in ((11, WIDE) if r else (11,)):
            raise SystemExit("gen_layouts: %s row %d has %d keys, a row has 11 (a letter row 11 or %d)"
                             % (lang, r, len(keys), WIDE))
        body += "".join(keys) + "    </Row>\n"
    files["lumen_%s.xml" % lang] = HEADER + KB_OPEN + body + BOTTOM + "</Keyboard>\n"
    return files


SPACE_RE = re.compile(r'(        <Key\n            android:codes="32"\n(?:            [^\n]*\n)*?'
                      r'            android:keyWidth=")@dimen/space_key_width(" />\n)')


def with_language_key(text):
    """An AOSP page with the language key before space (space keeps the space_key_width dimen, now 5 columns)."""
    if 'android:codes="-9"' in text:
        return text
    m = SPACE_RE.search(text)
    if not m:
        raise SystemExit("gen_layouts: no space key")
    return text[:m.start()] + LANG_KEY + text[m.start():]


def aosp_pages():
    return sorted(f for f in os.listdir(XML)
                  if re.match(r"(qwerty|qwertz|azerty|sym)[a-z_]*\.xml$", f))


def wanted():
    files = {}
    for lang, rows in LAYOUTS.items():
        files.update(layout_files(lang, rows))
    for f in aosp_pages():
        with open(os.path.join(XML, f), encoding="utf-8") as fh:
            files[f] = with_language_key(fh.read())
    return files


def main(argv):
    mode = argv[1] if len(argv) > 1 else ""
    if mode not in ("write", "check"):
        raise SystemExit(__doc__)
    bad = 0
    want = wanted()
    stale = [f for f in os.listdir(XML) if f.startswith("lumen_") and f not in want]
    for name, text in sorted(want.items()):
        p = os.path.join(XML, name)
        have = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if have == text:
            continue
        if mode == "write":
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(text)
            print("wrote", name)
        else:
            print("gen_layouts: %s is not what the table makes" % name)
            bad += 1
    for name in stale:
        if mode == "write":
            os.remove(os.path.join(XML, name))
            print("removed", name)
        else:
            print("gen_layouts: %s is not in the table" % name)
            bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
